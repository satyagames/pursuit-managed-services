// Writes SHAREPOINT-LISTS.md, the reference of the app's SharePoint lists, from the schema file (public/js/pms-schema.js and
// public/js/pms-schema-meta.js) and nothing else. Phase 10c-2b.
//
//   npm run build:lists-reference      write SHAREPOINT-LISTS.md
//   (scripts/test-lists-reference.js fails when the committed file is not what this would write)
//
// The words of the file are the schema's own (each list's and column's purpose) and the few fixed paragraphs below. To change what
// the reference says about a column, change pms-schema-meta.js and run this again: never edit SHAREPOINT-LISTS.md by hand.
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { ID, LIBRARY, LISTS, VERSION } from '../public/js/pms-schema.js';
import { LIBRARY_META, LOCAL_FILE, META, RETIRED, columnsOf } from '../public/js/pms-schema-meta.js';
import { SETUP_NOTE, participantGroups, permissionsTable } from './permissions.js';

export const REFERENCE_FILE = path.join(import.meta.dirname, '..', 'SHAREPOINT-LISTS.md');

const TYPE_WORDS = { Text: 'Single line of text', Note: 'Multiple lines of text, plain text (append-only off)', Number: 'Number', DateTime: 'Date and Time', Boolean: 'Yes/No' };
const yes = (value) => (value ? 'yes' : 'no');
const cell = (text) => String(text ?? '').replaceAll('|', '\\|').replaceAll('<', '&lt;').replaceAll('\n', ' ');
const roles = (list) => (list.length ? list.join(', ') : 'nobody');
const number = (value) => (typeof value === 'number' ? value.toLocaleString('en-US') : value);

/** The glossary: the code's words for the lists, and the screens'. */
const GLOSSARY = [
  ['`sections`', 'activities', 'PMSActivities'], ['`tracks`', 'participants / visits', 'PMSParticipants'], ['`qrtokens`', 'guest QR codes', 'PMSGuestQRCodes'],
  ['`visitorroster`', 'guest list', 'PMSGuestList'], ['`uservisitlogs`', 'visit log', 'PMSVisitLog'], ['`responses`', 'answers', 'PMSParticipantAnswers'],
];

/** SHAREPOINT-LISTS.md, as text. Pure. */
export function reference() {
  const lines = [];
  const add = (...more) => lines.push(...more);
  add('# SharePoint lists of Pursuit Managed Services',
    '',
    `<!-- Generated by scripts/build-lists-reference.js from public/js/pms-schema.js and public/js/pms-schema-meta.js. Do not edit by hand: change the schema file and run \`npm run build:lists-reference\` (scripts/test-lists-reference.js fails when this file is stale). -->`,
    '',
    `The app keeps everything in ${Object.keys(LISTS).length} SharePoint lists and one picture library on one site. This is the reference to every list and every column: what it is for, who uses it, and exactly how SharePoint must have it. It describes **schema version ${VERSION}**, the lists of the new site (Phase 10c-2b). The lists of the old site are described in PROVISIONING.md, which is kept as a record.`,
    '',
    '**Where it comes from.** One file says what every list and column is: `public/js/pms-schema.js` (the names, which every page carries) and `public/js/pms-schema-meta.js` (everything else, which only Setup, the tests and this generator read). The data layer, Setup\'s Check Lists, the mocked SharePoint of the tests, the local server and the seed checker are all built on it.',
    '',
    `**Titles and copies.** Each title below is the list's title when a copy of the app has no prefix (\`"listPrefix": ""\` in \`pms-config.txt\`, said on purpose: a page must be told its prefix). A copy with \`"listPrefix": "Test"\` uses \`Test${LISTS.clients.title}\` and so on, and \`Test${LIBRARY}\` for the pictures. A single list can also be given a title of its own (\`"lists": { "<key>": "<title>" }\`), and the library (\`"logoLibrary"\`). The key of each list (\`clients\`, \`sessions\`...) is the code's name for it and never changes.`,
    '',
    `**The version.** The item \`default\` of ${LISTS.appsettings.title} carries \`SchemaVersion\` (${VERSION} for these lists). Setup writes it when it makes the lists, and raises an earlier version once the check of this one is clean (Phase 10i); nothing else writes it, and no item is made by hand. Every page reads that item first, so the check costs no request: a missing item, a missing list or no version stops the participant and admin pages with PMS-LST-010, a lower version with PMS-LST-011, a higher one with PMS-LST-012; Setup opens and says which.`,
    '',
    '**Rules for every list.**',
    '',
    `- \`${ID}\` is the app's own id of an item (never SharePoint's numeric ID): single line of text, required, indexed, enforce unique values.`,
    '- Every column below must exist on its list, with exactly its internal name and type. No column but AppId is required to hold a value ("Require that this column contains information" is off): many are legitimately empty.',
    '- An index on exactly the columns the app filters on, and on no other column. A query on a column with no index fails once a list passes 5,000 items.',
    '- A column of chosen words is a single line of text, not a Choice: its allowed words are listed below and checked by the app.',
    '- Every date column shows **Date & Time**, never Date Only: a date-only value can be read back as the day before, by the site\'s time zone (SessionDate included).',
    '- A Yes/No column defaults to No. A single line of text holds 255 characters at most; where the app\'s own limit is lower it is given.',
    '- Ordered children are JSON lists of ids, kept as plain text of several lines; the app replaces the whole value on every write.',
    '- The built-in Title is filled by the app (the record\'s title, name or id). Content approval and attachments off unless policy requires them.',
    '',
    '## Glossary',
    '',
    'The code, the screens and the lists use different words for some lists.',
    '',
    '| In the code | On screen | List |',
    '|---|---|---|',
    ...GLOSSARY.map(([code, screen, title]) => `| ${code} | ${screen} | ${title} |`),
    '',
    '## The lists',
    '',
    '| Key | Title | What it is for | Read by | Written by | Items per event | Items per year (assumed) |',
    '|---|---|---|---|---|---|---|',
    ...Object.entries(META).map(([key, list]) => `| \`${key}\` | ${LISTS[key].title} | ${cell(list.purpose)} | ${roles(list.reads)} | ${roles(list.writes)} | ${cell(list.growth.perEvent)} | ${cell(list.growth.perYear)} |`),
    '',
    'Growth is an ASSUMPTION from ARCHITECTURE-10.md 4.1, in git history at 7347c72 (100 events a year with 60 people each), to be replaced with real figures. Tracks (participants), answers and the visit log pass 5,000 items in under a year at that volume: that is why the indexes matter.',
    '');
  for (const [key, list] of Object.entries(META)) {
    add(`## ${LISTS[key].title}`,
      '',
      `Key \`${key}\` (on the local server, \`server/data/${LOCAL_FILE[key] ?? key}.json\`). ${cell(list.purpose)} Read by ${roles(list.reads)}; written by ${roles(list.writes)}.`,
      '',
      '| Column | Type | Must exist | Indexed | Unique | Required | Allowed values | Longest | Default | Personal data | What it holds | Read by | Written by |',
      '|---|---|---|---|---|---|---|---|---|---|---|---|---|');
    for (const column of columnsOf(key)) {
      const type = `${TYPE_WORDS[column.type] ?? column.type}${column.format ? `, shown as ${column.format}` : ''}`;
      add(`| \`${column.name}\` | ${type} | ${yes(column.mustExist)} | ${yes(column.indexed)} | ${yes(column.unique)} | ${yes(column.required)} | ${column.values ? column.values.map((value) => `\`${value}\``).join(', ') : ''} | ${column.max ? number(column.max) : ''} | ${cell(column.default)} | ${column.personal ? '**yes**' : 'no'} | ${cell(column.purpose)} | ${roles(column.reads)} | ${roles(column.writes)} |`);
    }
    add('');
  }
  add('## Columns no longer used',
    '',
    'Version 3 (Phase 10i) renamed two columns. SharePoint gives every list item a property called `DisplayName`, and the real site (PCOE, 15 Oct 2026) would not return a column of that name when a read named it ("Value does not fall within the expected range."). A site made for an earlier version keeps its old column: nothing reads or writes it, the check does not look at it, and Setup never deletes it (its plan lists it as harmless); a site owner may delete it by hand. No column of the app may be named like a property SharePoint gives every list item: `scripts/test-schema.js` lists them.',
    '',
    '| List | Column | Last used in version | Its value is kept in, since |',
    '|---|---|---|---|',
    ...Object.entries(RETIRED).flatMap(([key, columns]) => columns.map((column) => `| ${LISTS[key].title} | \`${column.name}\` | ${column.lastIn} | \`${column.now}\` |`)),
    '');
  add(`## The picture library: ${LIBRARY}`,
    '',
    `A document library (not a folder in Shared Documents). ${LIBRARY_META.purpose} Read by ${roles(LIBRARY_META.reads)}; written by ${roles(LIBRARY_META.writes)}.`,
    '',
    `- **Naming:** \`${LIBRARY_META.naming.split(', ')[0]}\`, ${LIBRARY_META.naming.split(', ').slice(1).join(', ')}. A different picture has a different name, so an address never changes what it shows; the file a new picture replaces is moved to the recycle bin once nothing uses it.`,
    '- **What is stored:** PNG, JPEG or WebP only (never SVG), cropped and re-encoded in the browser first: hero 1200x1200 (300 KB), logo 800x400 (150 KB), background 1536x2048 (350 KB), answer tile 480x320 (60 KB); 512 KB at most.',
    '- **Permissions:** facilitators add files and recycle them; Setup\'s "Seed sample clients" adds the six sample pictures; every account that opens the participant page reads them.',
    '',
    '## Permissions',
    '',
    `Worked out from who reads and writes each list (the \`reads\` and \`writes\` of pms-schema-meta.js, by scripts/permissions.js; the release package\'s RUNBOOK.md has the same table). SharePoint has no "write but not read" for a list: a page that writes a list needs Contribute there, one that only reads it needs Read, and a list it does neither with is one its accounts must not be able to read. **Participant accounts must not read ${participantGroups().none.join(', ')}**: it holds the facilitators\' PIN hashes, and the PIN only gates the admin page\'s screens, so the list\'s permission is the real lock. A facilitator who also opens the participant page needs the participant accounts\' rights as well.`,
    '',
    permissionsTable(),
    '',
    SETUP_NOTE,
    '',
    '## How to change a list',
    '',
    '**To add a column:**',
    '',
    `1. Add the field to its list in \`public/js/pms-schema.js\`: the record's property, the column's internal name, its kind (text, \`number\`, \`yesno\`, \`date\`, \`array\`, \`object\`), and \`indexed\` if the app will filter on it.`,
    '2. Describe the column in `public/js/pms-schema-meta.js`, in the same place among its list\'s columns: its SharePoint type, its purpose in one sentence, and whatever applies of allowed values, longest value, default, who reads and writes it and whether it holds personal data.',
    '3. Write the code that uses the field (the data layer reads and writes every field of the schema by itself).',
    '4. Run `npm run build:lists-reference` and commit this file with the change. `npm test` (scripts/test-schema.js) fails if the two schema files disagree, and scripts/test-lists-reference.js if this file is stale.',
    '5. If lists already exist on a site, Setup adds the column there: **Show the plan** names it and **Create** makes it (or make it by hand, exactly as this file says). If the change is one an older build cannot work with, raise `VERSION` in pms-schema.js: on a site of the earlier version the pages then stop with PMS-LST-011 until Setup has run Show the plan, Create and Mark the site as ready, which raises the version once the check is clean (Phase 10i).',
    '',
    '**To add a list:** one entry, under a new key, in each of the two schema files (its title and fields; its purpose, readers, writers, growth and columns), the data layer\'s functions for it, a file of the same name under `server/data/` for the local server, then as above. The settings (`"lists"`) and the mocked SharePoint take a new key by themselves.',
    '');
  return lines.join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  await writeFile(REFERENCE_FILE, reference());
  console.log(`Wrote ${path.relative(process.cwd(), REFERENCE_FILE)}`);
}
