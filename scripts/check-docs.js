const tracked = execSync('git ls-files', { cwd: ROOT, encoding: 'utf8' }).trim().split('\n');
const trackedSet = new Set(tracked);
const folders = new Set(tracked.flatMap((file) => file.split('/').slice(0, -1).map((_, i, parts) => parts.slice(0, i + 1).join('/'))));
const basenames = new Set(tracked.map((file) => path.posix.basename(file)));
const exists = (p) => trackedSet.has(p) || folders.has(p.replace(/\/$/, ''));

/** Where a path in a document may be written from: the root, the app, its source, its lib, the scripts. */
const BASES = ['', 'migration/', 'migration/src/', 'migration/src/lib/', 'scripts/', 'docs/'];
/** Folders that are made by commands and are git-ignored: a path into one is not checked. */
const MADE = /^(build-svelte|test-results|ux-review|\.local|node_modules|playwright-report|scripts\/local-site\/(data|datasets\/images|\.cert))(\/|$)/;

/** GitHub's anchor for a heading. */
export const slug = (heading) => heading.trim().toLowerCase().replace(/<[^>]+>/g, '').replace(/[`*_~]/g, '').replace(/[^\p{L}\p{N}\s-]/gu, '').replace(/\s/g, '-');

function anchorsOf(file) {
  const seen = new Map();
  const anchors = new Set();
  let fenced = false;
  for (const line of readFileSync(path.join(ROOT, file), 'utf8').split(/\r?\n/)) {
    if (/^\s*```/.test(line)) fenced = !fenced;
    if (fenced) continue;
    const heading = /^#{1,6}\s+(.+?)\s*#*\s*$/.exec(line);
    if (!heading) continue;
    const base = slug(heading[1]);
    const count = seen.get(base) ?? 0;
    seen.set(base, count + 1);
    anchors.add(count ? `${base}-${count}` : base);
  }
  for (const match of readFileSync(path.join(ROOT, file), 'utf8').matchAll(/<a (?:name|id)="([^"]+)"/g)) anchors.add(match[1]);
  return anchors;
}

/** Is `token` (from inside backticks) a path or file name that the repository has? null when it is not a path at all. */
export function pathProblem(token) {
  if (/\(.*\)./.test(token) || /^[\w.]+\.(html|json)\(\)$/.test(token)) return null; // code, such as res.status().json or doc.html()
  let text = token.trim().replace(/:\d+(?::\d+)?$/, '').replace(/\(\)$/, '').replace(/^\.\//, '');
  if (!text || /[\s<>*{}$…|"'`=,;@]|\.\.\.|:\/\/|^#|^\.|^-|\/\/|[?&]/.test(text)) return null;
  if (GONE.has(text)) return null;
  const hasSlash = text.includes('/');
  const ext = /\.(js|mjs|cjs|ts|svelte|css|md|json|txt|py|html)$/.test(text);
  if (!hasSlash && !ext) return null;
  if (!hasSlash) return basenames.has(text) ? null : `no tracked file is called ${text}`;
  if (/^[a-z]+:/.test(text) || /^(https?|www)\b/.test(text)) return null;
  if (!/^(migration|scripts|server|public|docs|lib|src|styles|admin|components|routes|pager|setup|dev|unsupported|assets|charts|request-baseline|schema-baseline|migration-tests|local-site|rehearsal-tests|styleguide-tests|data|schema|settings|participant|common|results|exports|brand|effects)(\/|$)|^[\w.-]+\.(md|json|txt)$/.test(text)) return null;
  if (MADE.test(text)) return null;
  for (const base of BASES) if (exists(path.posix.normalize(base + text))) return null;
  return `nothing in the repository is at ${text}`;
}

export function checkDocs({ files } = {}) {
  const packageScripts = JSON.parse(readFileSync(path.join(ROOT, 'package.json'), 'utf8')).scripts;
  const { LISTS, LIBRARY } = schema;
  const titles = new Set([...Object.values(LISTS).map((list) => list.title), LIBRARY]);
  const documents = files ?? tracked.filter((file) => file.endsWith('.md') || file === 'llms.txt');
  const problems = [];
  for (const file of documents) {
    if (RECORDS.some((pattern) => pattern.test(file))) continue;
    const lines = readFileSync(path.join(ROOT, file), 'utf8').split(/\r?\n/);
    let fenced = false;
    lines.forEach((line, index) => {
      const at = `${file}:${index + 1}`;
      if (/^\s*```/.test(line)) { fenced = !fenced; return; }
      // Links to files of the repository, and their anchors.
      for (const match of line.matchAll(/\]\(([^)\s]+)(?:\s+"[^"]*")?\)/g)) {
        const target = match[1];
        if (/^(https?:|mailto:)/.test(target)) continue;
        const [where, anchor] = target.split('#');
        const resolved = where ? path.posix.normalize(path.posix.join(path.posix.dirname(file), decodeURIComponent(where))) : file;
        if (where && !exists(resolved)) { problems.push(`${at}: the link ${target} points at nothing`); continue; }
        if (anchor && resolved.endsWith('.md') && !anchorsOf(resolved).has(anchor)) problems.push(`${at}: the link ${target} names no heading of ${resolved}`);
      }
      for (const match of line.matchAll(/npm run ([\w:.-]*[\w])/g)) {
        if (!packageScripts[match[1]] && !GONE_SCRIPTS.has(match[1])) problems.push(`${at}: npm run ${match[1]} is not a script of package.json`);
      }
      if (fenced) return;
      // A sentence that names a document of an earlier phase says where it is: in git history (at 7347c72, or the tag legacy-final).
      if (/in git history|legacy-final/.test(line)) return;
      for (const match of line.matchAll(/`([^`]+)`/g)) {
        const problem = pathProblem(match[1]);
        if (problem) problems.push(`${at}: ${problem}`);
      }
      for (const match of line.replace(/`[^`]*`/g, (code) => code.replace(/\bPMS[A-Z]\w*\b/g, (title) => (titles.has(title) ? title : title))).matchAll(/(?<![\w-])PMS[A-Z][A-Za-z]+\b/g)) {
        if (!titles.has(match[0])) problems.push(`${at}: ${match[0]} is not a list or the library of the schema`);
      }
    });
  }
  return problems;
}

const schema = await import(pathToFileURL(path.join(ROOT, 'migration/src/lib/schema/pms-schema.js')).href);

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const problems = checkDocs();
  for (const problem of problems) console.log(problem);
  console.log(problems.length ? `\n${problems.length} problem(s) in the documents.` : 'The documents name only what is there.');
  process.exitCode = problems.length ? 1 : 0;
}
