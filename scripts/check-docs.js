// as it was) is read, and each of these must hold:
//   - a link to a file in the repository points at a file that exists, and an anchor at a heading that exists;
//   - a path in `code` (migration/src/lib/data/dataService.js, lib/results/results-tally.js, scripts/check-docs.js, src/admin/charts/) names a
//     file or folder that exists; a bare file name in `code` (boot.js) is the name of a tracked file;
//   - `npm run <script>` names a script of package.json;
//   - a list title such as PMSClients is a list or the library of the schema file.
// What a document names on purpose although it is gone (a file a phase removed, in a sentence that says so) is in GONE below, each with why.
// Run: node scripts/check-docs.js (prints every problem, and exits 1 if there is one). scripts/test-check-docs.js runs it in `npm test`.
